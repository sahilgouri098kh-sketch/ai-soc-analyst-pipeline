
import json
from pathlib import Path
from datetime import datetime, timezone

INPUT_FILE = Path("alerts/ai_triaged/triaged_alerts.jsonl")
OUTPUT_DIR = Path("reports")


def create_report(alert):
    alert_id = alert.get("alert_id", "UNKNOWN")
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    intel = alert.get("threat_intelligence", {})
    vt = intel.get("virustotal", {})
    abuse = intel.get("abuseipdb", {})

    actions = alert.get("recommended_actions", [])
    action_text = "\n".join(f"- [ ] {action}" for action in actions)
    if not action_text:
        action_text = "- [ ] Review the alert manually"

    report = f"""# SOC Incident Report: {alert_id}

## 1. Incident Summary

- **Alert ID:** {alert_id}
- **Generated:** {now}
- **Severity:** {alert.get('severity', 'Unknown')}
- **Triage verdict:** {alert.get('verdict', 'Not assessed')}
- **Attack type:** {alert.get('attack_type', 'Unknown')}
- **MITRE ATT&CK technique:** {alert.get('mitre_technique', 'Not mapped')}

## 2. Observed Evidence

- **Source IP:** {alert.get('source_ip', 'Unknown')}
- **Destination IP:** {alert.get('destination_ip', 'Unknown')}
- **Related events:** {alert.get('event_count', 0)}
- **Reasoning:** {alert.get('reasoning_summary', 'No reasoning provided')}

## 3. Threat Intelligence

- **VirusTotal status:** {vt.get('status', 'Not available')}
- **VirusTotal reputation:** {vt.get('reputation', 'Not available')}
- **VirusTotal malicious detections:** {vt.get('malicious', 'Not available')}
- **AbuseIPDB status:** {abuse.get('status', 'Not available')}
- **AbuseIPDB abuse score:** {abuse.get('abuse_confidence_score', 'Not available')}

> A skipped lookup is not evidence that an IP is benign or malicious.

## 4. Recommended Response Actions

{action_text}

## 5. Analyst Notes

- Validate the alert against underlying logs and network evidence.
- Confirm whether the activity is authorized or suspicious.
- Record investigation findings before closing or escalating the incident.

## 6. Limitations

This report is generated by a lab pipeline using rule-based triage.
Threat-intelligence lookups may be skipped or unavailable.
An analyst must validate the findings before making a final decision.
"""
    return report


def generate_reports():
    if not INPUT_FILE.exists():
        print(f"[-] Input file not found: {INPUT_FILE}")
        return

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    count = 0

    with INPUT_FILE.open("r") as infile:
        for line in infile:
            if not line.strip():
                continue
            try:
                alert = json.loads(line)
            except json.JSONDecodeError:
                print("[-] Skipping invalid JSON line")
                continue

            alert_id = alert.get("alert_id", f"UNKNOWN-{count + 1}")
            safe_id = "".join(
                char for char in alert_id
                if char.isalnum() or char in "-_"
            )
            output_file = OUTPUT_DIR / f"{safe_id}.md"
            output_file.write_text(create_report(alert), encoding="utf-8")
            count += 1

    print("[+] Incident report generation completed")
    print(f"[+] Reports generated: {count}")
    print(f"[+] Output directory: {OUTPUT_DIR}")


if __name__ == "__main__":
    generate_reports()
